/// ─────────────────────────────────────────────────────────────────────
/// 身份证件更新 Repository 抽象。
/// ─────────────────────────────────────────────────────────────────────
///
/// 【职责】
/// 定义身份更新数据操作的接口。
///
/// 【为什么需要抽象？】
/// 即便当前只有一个实现，抽象层仍然有价值：
/// 1. 依赖倒置：UseCase 依赖抽象，不依赖具体实现
/// 2. 易于测试：可以注入 Mock Repository
/// 3. 未雨绸缪：未来可能与本地数据库联动
///
abstract class IdentityUpdateRepository {
  /// 更新身份信息。
  ///
  /// [payload] 包含客户 ID、证件信息、活体认证结果、签名等。
  Future<void> updateIdentity(Map<String, dynamic> payload);
}
