import 'package:flutter/material.dart';

/// ─────────────────────────────────────────────────────────────────────
/// 应用颜色定义。
/// ─────────────────────────────────────────────────────────────────────
///
/// 【设计目标】
/// 统一管理颜色常量，确保全局一致性。
///
/// 【命名规范】
/// - 功能性颜色：primary、danger、success 等
/// - 语义性颜色：textPrimary、textSecondary、surface 等
/// - 避免使用具体颜色值命名（如 blue100），用语义代替
///
/// 【使用方式】
/// ```dart
/// Container(color: AppColors.primary);
/// Text('Hello', style: TextStyle(color: AppColors.textPrimary));
/// ```
///
class AppColors {
  AppColors._();

  // ═══════════════════════════════════════════════════════════════════════
  // 品牌色
  // ═══════════════════════════════════════════════════════════════════════

  /// 主色调（品牌色）。
  ///
  /// 用于：主按钮、重要图标、Tab 选中态等。
  static const primary = Color(0xFF176B5B);

  /// 强调色。
  ///
  /// 用于：链接、次要操作按钮等。
  static const accent = Color(0xFF3E7CB1);

  // ═══════════════════════════════════════════════════════════════════════
  // 功能色
  // ═══════════════════════════════════════════════════════════════════════

  /// 危险/错误色。
  ///
  /// 用于：错误提示、删除按钮、警示文字等。
  static const danger = Color(0xFFB42318);

  /// 成功色。
  ///
  /// 用于：成功提示、完成状态等。
  static const success = Color(0xFF0E8F4E);

  // ═══════════════════════════════════════════════════════════════════════
  // 中性色
  // ═══════════════════════════════════════════════════════════════════════

  /// 页面背景色。
  ///
  /// 用于：Scaffold 背景、卡片外围区域等。
  static const surface = Color(0xFFF7F8FA);

  /// 边框色。
  ///
  /// 用于：输入框边框、分割线、卡片边框等。
  static const border = Color(0xFFD8DEE6);

  // ═══════════════════════════════════════════════════════════════════════
  // 文字色
  // ═══════════════════════════════════════════════════════════════════════

  /// 主要文字色。
  ///
  /// 用于：标题、正文、重要信息等。
  static const textPrimary = Color(0xFF172026);

  /// 次要文字色。
  ///
  /// 用于：辅助说明、时间戳、占位符等。
  static const textSecondary = Color(0xFF5F6B7A);
}

